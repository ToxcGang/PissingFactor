test("engine pump advances once at each simulation interval",function()
    local p=Pump.new(0.1)
    local due,diagnostic,dt=p:step(0,false)
    equal(due,true);equal(diagnostic,false);near(dt,0.1)
    equal(p:step(0.05,false),false)
    equal(p:step(0.1,false),true)
    equal(p:step(0.1,false),false)
end)
test("held diagnostic key emits once and rapid presses are bounded",function()
    local p=Pump.new(0.1)
    local _,shown=p:step(0,true);equal(shown,true)
    for i=1,50 do local _,again=p:step(i/10,true);equal(again,false) end
    p:step(5.1,false)
    local _,again=p:step(5.2,true);equal(again,true)
    p:step(5.3,false)
    local _,rapid=p:step(5.4,true);equal(rapid,false)
    p:step(6.3,false)
    local _,later=p:step(6.4,true);equal(later,true)
end)
test("pump clock reset and stalls cannot schedule catch-up bursts",function()
    local p=Pump.new(0.1)
    p:step(10,false)
    local due,_,dt=p:step(70,false);equal(due,true);near(dt,0.1)
    equal(p:step(70,false),false)
    local reset,_,resetDt=p:step(1,false);equal(reset,true);near(resetDt,0.1)
