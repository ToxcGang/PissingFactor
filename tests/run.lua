test("arc stops at the first obstruction", function()
    local calls = 0
    local r = Trajectory.trace({X=0,Y=0,Z=100},aim,400,function(a,b)
        calls = calls + 1
        if calls == 3 then return {kind="solid",position=b} end
    end)
    equal(calls,3);equal(r.hit.kind,"solid")
end)
test("arc falls under gravity and respects total travel range", function()
    local r = Trajectory.trace({X=0,Y=0,Z=100},aim,400,function() end)
    assert(r.endpoint.Z < 100)
    local length = 0
    for i=2,#r.points do
        local a,b=r.points[i-1],r.points[i]
        length=length+math.sqrt((a.X-b.X)^2+(a.Y-b.Y)^2+(a.Z-b.Z)^2)
    end
    near(length,400)
end)
test("first water hit prevents staining the submerged floor", function()
